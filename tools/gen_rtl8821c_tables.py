#!/usr/bin/env python3
"""Regenerate libs/devices/rtl8821c_tables.h from the Realtek vendor driver.

usage: tools/gen_rtl8821c_tables.py <path-to-8821cu-vendor-driver> [out.h]

Pulls the phydm MAC/BB/AGC/RF register images (halhwimg8821c_*.c) verbatim. The
IF/ELSE IF/ELSE/ENDIF condition words are kept and evaluated at load time by
wchip_rtl8821cu.c (same rules as phydm's check_positive()).
"""
import os, re, sys

drv = sys.argv[1] if len(sys.argv) > 1 else "/Volumes/awsm/rep/8821cu-20210916"
out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(__file__), "..", "libs", "devices", "rtl8821c_tables.h")

src = {
    "mac_reg": "hal/phydm/rtl8821c/halhwimg8821c_mac.c",
    "phy_reg": "hal/phydm/rtl8821c/halhwimg8821c_bb.c",
    "agc_tab": "hal/phydm/rtl8821c/halhwimg8821c_bb.c",
    "agc_tab_diff_btg": "hal/phydm/rtl8821c/halhwimg8821c_bb.c",  # applied after agc_tab on BTG modules
    "agc_tab_diff_wlg": "hal/phydm/rtl8821c/halhwimg8821c_bb.c",
    "radioa":  "hal/phydm/halrf/rtl8821c/halhwimg8821c_rf.c",
}

out = ["#ifndef DEVICE_RTL8821C_TABLES_H", "#define DEVICE_RTL8821C_TABLES_H",
       "/* Generated by tools/gen_rtl8821c_tables.py from the Realtek 8821cu-20210916 vendor driver",
       " * (phydm halhwimg8821c_{mac,bb,rf}.c, Image2HeaderVersion R3 1.5.10.1). Conditional",
       " * (IF/ELSE IF/ELSE/ENDIF) entries are kept and evaluated at load time against",
       " * cut/package/interface/RFE, like phydm's check_positive(). Do not edit by hand. */",
       "#include <stdint.h>", ""]
for name, rel in src.items():
    text = open(os.path.join(drv, rel)).read()
    m = re.search(r"u32\s+array_mp_8821c_%s\[\]\s*=\s*\{(.*?)\};" % name, text, re.S)
    if not m:
        sys.exit("array_mp_8821c_%s not found in %s" % (name, rel))
    vals = [v.upper().replace("0X", "0x") for v in re.findall(r"0x[0-9a-fA-F]+", m.group(1))]
    out.append("static const uint32_t rtl8821c_%s[] = {" % name)
    for i in range(0, len(vals), 8):
        out.append("  " + ", ".join(vals[i:i + 8]) + ",")
    out.append("};")
    out.append("")
    print("%-8s %5d words" % (name, len(vals)))
out.append("#endif")
open(out_path, "w").write("\n".join(out) + "\n")
